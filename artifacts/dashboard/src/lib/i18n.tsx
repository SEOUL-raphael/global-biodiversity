const LangContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: keyof typeof T) => string;
}>({
  lang: "ko",
  setLang: () => {},
  t: (k) => T[k]?.ko ?? String(k),
});

const SUPPORTED: Lang[] = ["ko", "en", "fr", "es", "ru", "zh", "ar"];

function detectInitialLang(): Lang {
  if (typeof window === "undefined") return "ko";
  const url = new URLSearchParams(window.location.search).get("lang");
  if (url && SUPPORTED.includes(url as Lang)) return url as Lang;
  const stored = localStorage.getItem("gbif:lang");
  if (stored && SUPPORTED.includes(stored as Lang)) return stored as Lang;
  const nav = (navigator.language || "en").toLowerCase().split("-")[0];
  if (SUPPORTED.includes(nav as Lang)) return nav as Lang;
  return "en";
}

function applyHtmlAttrs(lang: Lang) {
  if (typeof document === "undefined") return;
  const html = document.documentElement;
  html.setAttribute("lang", LANG_HTML[lang].lang);
  html.setAttribute("dir", LANG_HTML[lang].dir);
  document.title = T.metaTitle[lang];
  let desc = document.querySelector('meta[name="description"]');
  if (!desc) {
    desc = document.createElement("meta");
    desc.setAttribute("name", "description");
    document.head.appendChild(desc);
  }
  desc.setAttribute("content", T.metaDescription[lang]);
  // Open Graph
  const ogPairs: Array<[string, string]> = [
    ["og:title", T.metaTitle[lang]],
    ["og:description", T.metaDescription[lang]],
    ["og:type", "website"],
    ["og:locale", LANG_HTML[lang].lang],
    ["twitter:card", "summary_large_image"],
    ["twitter:title", T.metaTitle[lang]],
    ["twitter:description", T.metaDescription[lang]],
  ];
  for (const [prop, content] of ogPairs) {
    const sel = prop.startsWith("og:")
      ? `meta[property="${prop}"]`
      : `meta[name="${prop}"]`;
    let el = document.querySelector(sel);
    if (!el) {
      el = document.createElement("meta");
      if (prop.startsWith("og:")) el.setAttribute("property", prop);
      else el.setAttribute("name", prop);
      document.head.appendChild(el);
    }
    el.setAttribute("content", content);
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectInitialLang);
  useEffect(() => {
    if (typeof window !== "undefined") localStorage.setItem("gbif:lang", lang);
    applyHtmlAttrs(lang);
  }, [lang]);
  const setLang = (l: Lang) => setLangState(l);
  const t = (k: keyof typeof T) => T[k]?.[lang] ?? T[k]?.en ?? String(k);
  return (
    <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}
